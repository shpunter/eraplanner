import { readFileSync, writeFileSync, mkdirSync, existsSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const castlesDir = join(__dirname, "../../castles/src/shared/castles");
const outFile = join(__dirname, "../src/routes/faction/castles.seo.ts");

const factions = ["hive", "necropolis", "grove", "dungeon", "temple", "schism"];

// Matches description value whether it's on the same line or the next:
//   description: "value"
//   description:\n      "value"
const descriptionRe = /description:\s*\n?\s*"([^"]+)"/g;
const nameRe = /\bname:\s*"([^"]+)"/g;

function extract(source) {
  const names = [...source.matchAll(nameRe)].map((m) => m[1]);
  const descriptions = [...source.matchAll(descriptionRe)].map((m) => m[1]);

  if (names.length !== descriptions.length) {
    throw new Error(
      `name/description count mismatch: ${names.length} names, ${descriptions.length} descriptions`
    );
  }

  return names.map((name, i) => ({ name, description: descriptions[i] }));
}

if (!existsSync(castlesDir)) {
  console.log("Castles MFE not found — using committed castles.seo.ts");
  process.exit(0);
}

const result = {};
for (const faction of factions) {
  const source = readFileSync(join(castlesDir, `${faction}.ts`), "utf-8");
  result[faction] = extract(source);
}

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(
  outFile,
  `// Auto-generated by scripts/gen-castles-seo.mjs — do not edit\nexport const castlesSeo = ${JSON.stringify(result, null, 2)} as const;\n`
);

const total = Object.values(result).reduce((s, arr) => s + arr.length, 0);
console.log(`Generated castles.seo.ts — ${total} buildings across ${factions.length} factions`);
